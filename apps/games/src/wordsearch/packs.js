/** Pick `count` distinct words from a bank for this level. Same seed, same words; a new seed, a new set. */
export function pickWords(bank, level, seed) {
  const cfg = LEVEL_CFG[level] || LEVEL_CFG.medium;
  const rand = mulberry32(seed ^ 0x9e3779b9);
  const shuffle = a => { const x = a.slice(); for (let i = x.length - 1; i > 0; i--) { const j = (rand() * (i + 1)) | 0; [x[i], x[j]] = [x[j], x[i]]; } return x; };
  const unique = [...new Set(bank)];
  const fits = unique.filter(x => x.length >= cfg.min && x.length <= cfg.max);
  const picked = shuffle(fits).slice(0, cfg.count);
  if (picked.length < cfg.count) {                         // a thin bank: top up with the closest lengths
    const mid = (cfg.min + cfg.max) / 2;
    const rest = shuffle(unique.filter(x => !picked.includes(x))).sort((a, b) => Math.abs(a.length - mid) - Math.abs(b.length - mid));
    picked.push(...rest.slice(0, cfg.count - picked.length));
  }
  return picked;
}

/** A playable puzzle definition for a category, level and seed. */
export function buildRound(pack, level, seed) {
  const cfg = LEVEL_CFG[level] || LEVEL_CFG.medium;
  return {
    title: `${pack.title} · ${cfg.label}`,
    words: pickWords(pack.words, level, seed),
    size: cfg.size, level, seed, message: ''
  };
}

/** One puzzle a day per level, the same for everybody: the date picks the category and the seed. */
export function dailyDef(level = 'medium', date = new Date()) {
  const y = date.getFullYear(), m = date.getMonth() + 1, d = date.getDate();
  const day = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  const pack = PACKS[(day + hashString(level)) % PACKS.length];
  const def = buildRound(pack, level, day * 7919 + 13);
  return { ...def, title: `Daily · ${pack.title} · ${LEVEL_CFG[level].label}`, daily: `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}` };
}
